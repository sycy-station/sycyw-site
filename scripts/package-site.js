#!/usr/bin/env node
"use strict";
// Production packaging leaves editable sources and development URLs intact.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const zlib = require("zlib");
const ROOT = path.resolve(__dirname, "..");
const DIST = path.join(ROOT, "dist");
const { PAGES } = require("../src/content/pages.js");
const pages = ["index", ...PAGES.map(p => p.slug), "system-design", "interaction", "brand", "motion", "archive"];
const digest = buffer => crypto.createHash("sha256").update(buffer).digest("hex").slice(0, 12);
if (fs.existsSync(DIST) && !fs.existsSync(path.join(DIST, ".site-build"))) {
  throw new Error("dist exists without a build marker; move it aside before packaging");
}
fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(DIST, { recursive: true });
fs.writeFileSync(path.join(DIST, ".site-build"), "Generated by scripts/package-site.js\n");
const assets = new Map();
const emitted = new Set();
const write = (file, buffer) => {
  const target = path.join(DIST, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, buffer);
  if (/\.(?:html|css|js|json|xml|txt|svg)$/.test(file)) {
    fs.writeFileSync(target + ".gz", zlib.gzipSync(buffer, { level: 6 }));
    fs.writeFileSync(target + ".br", zlib.brotliCompressSync(buffer, {
      params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 5 }
    }));
  }
};
const emitAsset = reference => {
  const file = reference.split(/[?#]/)[0];
  if (emitted.has(file)) return file;
  if (assets.has(file)) return assets.get(file);
  if (!file.startsWith("assets/") || file.includes("..")) throw new Error(`Invalid asset: ${file}`);
  const buffer = fs.readFileSync(path.join(ROOT, file));
  const extension = path.posix.extname(file);
  const output = `${file.slice(0, -extension.length)}.${digest(buffer)}${extension}`;
  write(output, buffer);
  assets.set(file, output);
  emitted.add(output);
  return output;
};
const cssPattern = /<link\b[^>]*rel="stylesheet"[^>]*>/g;
const home = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");
const cssLinks = home.match(cssPattern) || [];
const cssFiles = cssLinks.map(link => link.match(/href="([^"]+)"/)[1].split("?")[0]);
const css = cssFiles.map(file => {
  let source = fs.readFileSync(path.join(ROOT, file), "utf8");
  source = source.replace(/url\(\s*(["']?)([^)"']+)\1\s*\)/g, (match, quote, url) => {
    if (/^(?:data:|https?:|\/\/|#)/.test(url)) return match;
    const asset = path.posix.normalize(path.posix.join(path.posix.dirname(file), url));
    return `url(${quote}${path.posix.relative("assets", emitAsset(asset))}${quote})`;
  });
  return `/* ${file} */\n${source}\n`;
}).join("\n");
const cssOutput = `assets/site.${digest(Buffer.from(css))}.css`;
write(cssOutput, Buffer.from(css));
emitted.add(cssOutput);
for (const slug of pages) {
  let html = fs.readFileSync(path.join(ROOT, slug + ".html"), "utf8");
  let linked = false;
  const links = html.match(cssPattern) || [];
  if (links.length && links.join("\n") !== cssLinks.join("\n")) throw new Error(`Unexpected stylesheet order: ${slug}`);
  html = html.replace(cssPattern, () => {
    if (linked) return "";
    linked = true;
    return `<link rel="stylesheet" href="${cssOutput}">`;
  });
  // Also rewrite the room-module JSON map, not just HTML attributes.
  html = html.replace(/\b(srcset|data-srcset)="([^"]+)"/g, (_, attribute, candidates) =>
    `${attribute}="${candidates.replace(/assets\/[^,\s]+/g, emitAsset)}"`);
  html = html.replace(/(["'])(assets\/[^"'<>\s]+)\1/g, (_, quote, reference) => `${quote}${emitAsset(reference)}${quote}`);
  write(slug + ".html", Buffer.from(html));
}
for (const file of ["robots.txt", "favicon.ico"]) write(file, fs.readFileSync(path.join(ROOT, file)));
if (require("../src/content/pages.js").SITE_URL && fs.existsSync(path.join(ROOT, "sitemap.xml"))) {
  write("sitemap.xml", fs.readFileSync(path.join(ROOT, "sitemap.xml")));
}
write("asset-manifest.json", Buffer.from(JSON.stringify(Object.fromEntries(assets), null, 2) + "\n"));
console.log(`Production: dist/ (${pages.length} pages, ${assets.size} fingerprinted assets, one stylesheet in original cascade order; gzip + Brotli ready)`);
